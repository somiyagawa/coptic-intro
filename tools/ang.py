ANS = lambda keep: keep + '。' + S(g['ang'], g['ousah'], g['an']) + '（主語が「私」なので、短い形 ' + ANG + ' を使います）。'

def answers(t):
    """練習 4-2 の三つ目（私は教師ではない）を短い形にする。付録B と、課の中の解答の両方"""
    i, j = section(t, 'apxB'); s = t[i:j]
    m = re.search(r'<p>4-2 ((?:(?!</p>).)*)</p>', s, re.S); assert m
    parts = m.group(1).split('</span>。<span class="copt" lang="cop">')
    assert len(parts) == 3 and 'ⲟⲩⲥⲁϩ' in parts[2], len(parts)
    keep = parts[0] + '</span>。<span class="copt" lang="cop">' + parts[1] + '</span>'
    t = t[:i] + s[:m.start(1)] + ANS(keep) + s[m.end(1):] + t[j:]
    def f(s):
        a = s.index('<div class="ans" hidden><p>', s.index('data-ex="4-2"')) + len('<div class="ans" hidden><p>'); b = s.index('</p></div>', a)
        assert 'ⲟⲩⲥⲁϩ' in s[a:b]
        return s[:a] + ANS(keep) + s[b:]
    return edit(t, 'l4', f)

