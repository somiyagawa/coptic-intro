sc = lambda s: re.sub(r'\{([^}]*)\}', r'<i class="sc">\1</i>', s)
def W(w, lat, kana):
    """転写とカナだけを持つ語"""
    return ('<span class="rb"><span class="rt" aria-hidden="true"><span class="rl">%s</span><span class="rk">%s</span></span>'
            '<span class="rw">%s</span></span>') % (lat, kc(kana), w)
def G(w0, w1, lat, kana, gl, gp=''):
    """グロスを持つ語（w0：区切らない形、w1：区切った形）"""
    return ('<span class="rb g"><span class="rbi"><span class="rt" aria-hidden="true"><span class="rl">%s</span><span class="rk">%s</span></span>'
            '<span class="rw"><span class="w0">%s</span><span class="w1">%s</span></span></span><span class="gl">%s</span>%s</span>') % (
            lat, kc(kana), w0, w1, sc(gl), '<span class="gp">%s</span>' % gp if gp else '')
C = lambda *xs: '<span class="copt" lang="cop">' + ''.join(xs) + '</span>'
S = lambda *xs: C(' '.join(xs))          # 語を空白で並べた一続きの例

def section(t, sid):
    i = t.index('<section class="view lesson" id="%s"' % sid); return i, t.index('</section>', i)
def edit(t, sid, fn):
    i, j = section(t, sid); return t[:i] + fn(t[i:j]) + t[j:]
def one(s, a, b):
    assert s.count(a) == 1, (s.count(a), a[:80]); return s.replace(a, b)
def li(s, title):
    """<strong>title</strong> で始まる項目の範囲"""
    a = '<li><strong>%s</strong>' % title
    assert s.count(a) == 1, (s.count(a), title); i = s.index(a); return i, s.index('</li>', i) + 5

