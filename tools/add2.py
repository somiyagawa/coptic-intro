def plain(h):
    h = re.sub(r'<span class="rt" aria-hidden="true">.*?</span></span>', '', h, flags=re.S)
    return re.sub(r'<[^>]+>', '', h)
def section(t, sid):
    i = t.index('<section class="view lesson" id="%s"' % sid); return i, t.index('</section>', i)
def edit(t, sid, fn):
    i, j = section(t, sid); return t[:i] + fn(t[i:j]) + t[j:]
def li_span(s, key, start=0):
    for m in re.finditer(r'<li><strong>(.*?)</strong>', s[start:], flags=re.S):
        if plain(m.group(1)).startswith(key):
            a = start + m.start(); return a, s.index('</li>', a) + 5
    raise KeyError(key)
def after(s, key, new, start=0):
    a, b = li_span(s, key, start); return s[:b] + '\n' + new + s[b:]
def rows(s, anchor, new):
    i = s.index(anchor); k = s.index('</tbody>', i); return s[:k] + new + '\n' + s[k:]
def td(x): return '<td>%s</td>' % x
def tr(*c): return '<tr>\n' + '\n'.join(td(x) for x in c) + '\n</tr>'
def card(title, body): return '<li><strong>%s</strong>：%s</li>' % (title, body)
def table(head, body):
    return ('<div class="tbl"><table>\n<thead>\n<tr>\n' + '\n'.join('<th>%s</th>' % h for h in head) + '\n</tr>\n</thead>\n<tbody>\n'
            + '\n'.join(body) + '\n</tbody>\n</table></div>')
